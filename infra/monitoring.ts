/*
 * nolie-engineering note, not in the original file; the code below is as it ran.
 *
 * The cluster, the two services, the load balancer and the target group come
 * from ecs.ts in this folder. Everything else is plumbing.
 */

import * as aws from "@pulumi/aws";
import * as pulumi from "@pulumi/pulumi";
import { alb, apiService, apiTargetGroup, cluster, workerService } from "./ecs";
import { redisCluster } from "./redis";
import { vpc } from "./vpc";

const stack = pulumi.getStack();
const config = new pulumi.Config();

const monitoringEnabled =
	config.getBoolean("monitoringEnabled") ?? stack === "prod";

if (monitoringEnabled) {
	const slackWorkspaceId = config.get("slackWorkspaceId");
	const slackChannelId = config.get("slackChannelId");

	// =========================================================================
	// SNS Topic
	// =========================================================================

	const alertsTopic = new aws.sns.Topic(`nolie-alerts-${stack}`, {
		tags: { Environment: stack },
	});

	exports.alertsTopicArn = alertsTopic.arn;

	// =========================================================================
	// AWS Chatbot (Amazon Q Developer) → Slack Integration
	// =========================================================================

	if (slackWorkspaceId && slackChannelId) {
		const chatbotRole = new aws.iam.Role(`nolie-chatbot-${stack}`, {
			assumeRolePolicy: JSON.stringify({
				Version: "2012-10-17",
				Statement: [
					{
						Action: "sts:AssumeRole",
						Effect: "Allow",
						Principal: { Service: "chatbot.amazonaws.com" },
					},
				],
			}),
		});

		new aws.iam.RolePolicy(`nolie-chatbot-policy-${stack}`, {
			role: chatbotRole.name,
			policy: JSON.stringify({
				Version: "2012-10-17",
				Statement: [
					{
						Effect: "Allow",
						Action: [
							"cloudwatch:Describe*",
							"cloudwatch:Get*",
							"cloudwatch:List*",
						],
						Resource: "*",
					},
				],
			}),
		});

		new aws.chatbot.SlackChannelConfiguration(`nolie-slack-alerts-${stack}`, {
			configurationName: `nolie-alerts-${stack}`,
			iamRoleArn: chatbotRole.arn,
			slackChannelId: slackChannelId,
			slackTeamId: slackWorkspaceId,
			snsTopicArns: [alertsTopic.arn],
			loggingLevel: "ERROR",
		});
	}

	// =========================================================================
	// CloudWatch Alarms
	// =========================================================================
	// Derived dimensions
	const clusterName = cluster.name;
	const apiServiceName = apiService.service.name;
	const workerServiceName = workerService.service.name;
	const albArnSuffix = alb.arnSuffix;
	const targetGroupArnSuffix = apiTargetGroup.arnSuffix;
	const redisCacheClusterId = redisCluster.clusterId;

	// Look up NAT Gateways by VPC ID
	const natGatewayIds = vpc.vpcId.apply((vpcId) =>
		aws.ec2.getNatGateways({ vpcId }).then((r) => r.ids),
	);

	// =========================================================================
	// Critical Alarms
	// =========================================================================

	// 1. API has zero healthy targets
	// Container Insights is disabled (cost), so RunningTaskCount does not exist.
	// ALB health is the truer outage signal anyway. Missing data means the target
	// group has no registered targets at all, which is the same outage.
	new aws.cloudwatch.MetricAlarm(`api-tasks-down-${stack}`, {
		alarmDescription:
			"[CRITICAL] API has zero healthy targets behind the ALB. Complete outage.",
		namespace: "AWS/ApplicationELB",
		metricName: "HealthyHostCount",
		dimensions: {
			TargetGroup: targetGroupArnSuffix,
			LoadBalancer: albArnSuffix,
		},
		statistic: "Minimum",
		period: 60,
		evaluationPeriods: 1,
		datapointsToAlarm: 1,
		comparisonOperator: "LessThanThreshold",
		threshold: 1,
		treatMissingData: "breaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 2. Worker has zero running tasks
	// Without Container Insights there is no RunningTaskCount, and the worker has
	// no ALB. A service with zero tasks publishes no AWS/ECS datapoints at all,
	// so metric absence (treatMissingData: breaching) IS the zero-tasks signal;
	// the threshold can never trigger on real data.
	new aws.cloudwatch.MetricAlarm(`worker-tasks-down-${stack}`, {
		alarmDescription:
			"[CRITICAL] Worker service is publishing no metrics, meaning zero running tasks. Jobs are not being processed.",
		namespace: "AWS/ECS",
		metricName: "CPUUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: workerServiceName,
		},
		statistic: "SampleCount",
		period: 60,
		evaluationPeriods: 2,
		datapointsToAlarm: 2,
		comparisonOperator: "LessThanThreshold",
		threshold: 1,
		treatMissingData: "breaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 3. ALB 5XX Errors (generated by ALB itself, not the app)
	new aws.cloudwatch.MetricAlarm(`alb-5xx-${stack}`, {
		alarmDescription:
			"[CRITICAL] ALB is generating 5XX errors — targets may be unreachable",
		namespace: "AWS/ApplicationELB",
		metricName: "HTTPCode_ELB_5XX_Count",
		dimensions: {
			LoadBalancer: albArnSuffix,
		},
		statistic: "Sum",
		period: 60,
		evaluationPeriods: 3,
		datapointsToAlarm: 3,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 10,
		treatMissingData: "notBreaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 4. ALB Unhealthy Targets
	new aws.cloudwatch.MetricAlarm(`alb-unhealthy-targets-${stack}`, {
		alarmDescription:
			"[CRITICAL] ALB has unhealthy targets — capacity is degraded",
		namespace: "AWS/ApplicationELB",
		metricName: "UnHealthyHostCount",
		dimensions: {
			TargetGroup: targetGroupArnSuffix,
			LoadBalancer: albArnSuffix,
		},
		statistic: "Minimum",
		period: 60,
		evaluationPeriods: 3,
		datapointsToAlarm: 3,
		comparisonOperator: "GreaterThanOrEqualToThreshold",
		threshold: 1,
		treatMissingData: "notBreaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 5. API Memory Critical (any single task near OOM)
	new aws.cloudwatch.MetricAlarm(`api-memory-critical-${stack}`, {
		alarmDescription: "[CRITICAL] API task memory > 95% — OOM kill imminent",
		namespace: "AWS/ECS",
		metricName: "MemoryUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: apiServiceName,
		},
		statistic: "Maximum",
		period: 60,
		evaluationPeriods: 3,
		datapointsToAlarm: 3,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 95,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 6. Worker Memory Critical (any single task near OOM)
	new aws.cloudwatch.MetricAlarm(`worker-memory-critical-${stack}`, {
		alarmDescription: "[CRITICAL] Worker task memory > 95% — OOM kill imminent",
		namespace: "AWS/ECS",
		metricName: "MemoryUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: workerServiceName,
		},
		statistic: "Maximum",
		period: 60,
		evaluationPeriods: 3,
		datapointsToAlarm: 3,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 95,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 7. Redis Engine CPU Critical
	new aws.cloudwatch.MetricAlarm(`redis-cpu-critical-${stack}`, {
		alarmDescription:
			"[CRITICAL] Redis engine CPU > 90% — commands are queuing, latency spikes expected",
		namespace: "AWS/ElastiCache",
		metricName: "EngineCPUUtilization",
		dimensions: {
			CacheClusterId: redisCacheClusterId,
			CacheNodeId: "0001",
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 90,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 8. Redis Memory Critical
	new aws.cloudwatch.MetricAlarm(`redis-memory-critical-${stack}`, {
		alarmDescription:
			"[CRITICAL] Redis memory usage > 80% — risk of evictions or write failures",
		namespace: "AWS/ElastiCache",
		metricName: "DatabaseMemoryUsagePercentage",
		dimensions: {
			CacheClusterId: redisCacheClusterId,
			CacheNodeId: "0001",
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 80,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 9. Redis Evictions
	new aws.cloudwatch.MetricAlarm(`redis-evictions-${stack}`, {
		alarmDescription:
			"[CRITICAL] Redis is evicting keys — memory pressure, risk of lost BullMQ job data",
		namespace: "AWS/ElastiCache",
		metricName: "Evictions",
		dimensions: {
			CacheClusterId: redisCacheClusterId,
			CacheNodeId: "0001",
		},
		statistic: "Sum",
		period: 300,
		evaluationPeriods: 3,
		datapointsToAlarm: 3,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 0,
		treatMissingData: "notBreaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 10. NAT Gateway Port Exhaustion (one alarm per gateway)
	natGatewayIds.apply((ids) => {
		ids.forEach((natGatewayId, i) => {
			new aws.cloudwatch.MetricAlarm(`nat-port-exhaustion-${i}-${stack}`, {
				alarmDescription: `[CRITICAL] NAT Gateway ${i} port allocation errors — outbound connections failing`,
				namespace: "AWS/NATGateway",
				metricName: "ErrorPortAllocation",
				dimensions: {
					NatGatewayId: natGatewayId,
				},
				statistic: "Sum",
				period: 300,
				evaluationPeriods: 3,
				datapointsToAlarm: 3,
				comparisonOperator: "GreaterThanThreshold",
				threshold: 0,
				treatMissingData: "notBreaching",
				alarmActions: [alertsTopic.arn],
				okActions: [alertsTopic.arn],
				tags: { Environment: stack },
			});
		});
	});

	// =========================================================================
	// Warning Alarms
	// =========================================================================

	// 11. API CPU High
	new aws.cloudwatch.MetricAlarm(`api-cpu-high-${stack}`, {
		alarmDescription:
			"[WARNING] API average CPU > 80% — autoscaling may not be keeping up",
		namespace: "AWS/ECS",
		metricName: "CPUUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: apiServiceName,
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 80,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 12. API Memory High
	new aws.cloudwatch.MetricAlarm(`api-memory-high-${stack}`, {
		alarmDescription:
			"[WARNING] API average memory > 80% — potential memory leak",
		namespace: "AWS/ECS",
		metricName: "MemoryUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: apiServiceName,
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 80,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 13. Worker CPU High
	new aws.cloudwatch.MetricAlarm(`worker-cpu-high-${stack}`, {
		alarmDescription:
			"[WARNING] Worker average CPU > 85% — may need to increase max capacity",
		namespace: "AWS/ECS",
		metricName: "CPUUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: workerServiceName,
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 85,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 14. Worker Memory High
	new aws.cloudwatch.MetricAlarm(`worker-memory-high-${stack}`, {
		alarmDescription:
			"[WARNING] Worker average memory > 80% — potential memory leak",
		namespace: "AWS/ECS",
		metricName: "MemoryUtilization",
		dimensions: {
			ClusterName: clusterName,
			ServiceName: workerServiceName,
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 80,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 15. Target 5XX Errors (from your application, not ALB)
	new aws.cloudwatch.MetricAlarm(`target-5xx-${stack}`, {
		alarmDescription:
			"[WARNING] Application returning elevated 5XX errors — check Sentry for details",
		namespace: "AWS/ApplicationELB",
		metricName: "HTTPCode_Target_5XX_Count",
		dimensions: {
			LoadBalancer: albArnSuffix,
		},
		statistic: "Sum",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 50,
		treatMissingData: "notBreaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 16. API p99 Latency
	new aws.cloudwatch.MetricAlarm(`api-p99-latency-${stack}`, {
		alarmDescription:
			"[WARNING] API p99 response time > 2s — user experience degraded",
		namespace: "AWS/ApplicationELB",
		metricName: "TargetResponseTime",
		dimensions: {
			LoadBalancer: albArnSuffix,
		},
		extendedStatistic: "p99",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 2,
		treatMissingData: "notBreaching",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 17. Redis CPU Warning
	new aws.cloudwatch.MetricAlarm(`redis-cpu-warning-${stack}`, {
		alarmDescription:
			"[WARNING] Redis engine CPU > 65% — consider scaling up node type",
		namespace: "AWS/ElastiCache",
		metricName: "EngineCPUUtilization",
		dimensions: {
			CacheClusterId: redisCacheClusterId,
			CacheNodeId: "0001",
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 5,
		datapointsToAlarm: 5,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 65,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// 18. Redis Connections High
	new aws.cloudwatch.MetricAlarm(`redis-connections-high-${stack}`, {
		alarmDescription:
			"[WARNING] Redis connections > 1000 — possible connection leak",
		namespace: "AWS/ElastiCache",
		metricName: "CurrConnections",
		dimensions: {
			CacheClusterId: redisCacheClusterId,
			CacheNodeId: "0001",
		},
		statistic: "Average",
		period: 60,
		evaluationPeriods: 10,
		datapointsToAlarm: 10,
		comparisonOperator: "GreaterThanThreshold",
		threshold: 1000,
		treatMissingData: "missing",
		alarmActions: [alertsTopic.arn],
		okActions: [alertsTopic.arn],
		tags: { Environment: stack },
	});

	// =========================================================================
	// Cost Guardrails (account-level, created once via the prod stack)
	// =========================================================================
	// Budget tracks GROSS usage (includeCredit: false). With Activate credits
	// applied, net spend is $0, so a default budget would never fire.

	const budgetAlertEmail = config.get("budgetAlertEmail");

	if (budgetAlertEmail) {
		new aws.budgets.Budget("nolie-monthly-cost", {
			budgetType: "COST",
			limitAmount: "400",
			limitUnit: "USD",
			timeUnit: "MONTHLY",
			costTypes: {
				includeCredit: false,
				includeRefund: false,
			},
			notifications: [
				{
					comparisonOperator: "GREATER_THAN",
					threshold: 80,
					thresholdType: "PERCENTAGE",
					notificationType: "ACTUAL",
					subscriberEmailAddresses: [budgetAlertEmail],
				},
				{
					comparisonOperator: "GREATER_THAN",
					threshold: 100,
					thresholdType: "PERCENTAGE",
					notificationType: "FORECASTED",
					subscriberEmailAddresses: [budgetAlertEmail],
				},
			],
		});

		// No AnomalyMonitor here: AWS auto-creates Default-Services-Monitor and
		// the account limit is one dimensional monitor, so creating another fails
		// (broke prod deploy 2026-07-26). Its Default-Services-Subscription
		// already emails ops@nolie.com daily.
	}

	// 19. NAT Gateway Packets Dropped (one alarm per gateway)
	natGatewayIds.apply((ids) => {
		ids.forEach((natGatewayId, i) => {
			new aws.cloudwatch.MetricAlarm(`nat-packets-dropped-${i}-${stack}`, {
				alarmDescription: `[WARNING] NAT Gateway ${i} dropping packets — throughput issue`,
				namespace: "AWS/NATGateway",
				metricName: "PacketsDropCount",
				dimensions: {
					NatGatewayId: natGatewayId,
				},
				statistic: "Sum",
				period: 300,
				evaluationPeriods: 3,
				datapointsToAlarm: 3,
				comparisonOperator: "GreaterThanThreshold",
				threshold: 100,
				treatMissingData: "notBreaching",
				alarmActions: [alertsTopic.arn],
				okActions: [alertsTopic.arn],
				tags: { Environment: stack },
			});
		});
	});
}
